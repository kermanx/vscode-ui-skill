// Lead-owned verification harness for the seven display components.
// Bundles every `mount*` export found in internal-docs/reference/*.ts into a
// standalone page (/reference/standalone.html) that mirrors main.ts' shell, so
// parity tests can run before the shared fixtures are registered by the main agent.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../../../components/', import.meta.url));
const at = path => resolve(root, path);
const referenceDir = at('../internal-docs/reference');
const { build } = createRequire(at('package.json'))('esbuild');

const kindOf = name => name.slice('mount'.length).replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
// Only this Lead's seven components, so a teammate's in-progress fixture can never break this bundle.
const allowed = new Set((process.env.STANDALONE_KINDS ?? 'codicon,highlighted-label,icon-label,keybinding-label,count-badge,progress-bar,loading-indicator').split(','));
const modules = [];
for (const entry of (await readdir(referenceDir)).sort()) {
  if (!entry.endsWith('.ts') || entry === 'theme-entry.ts') continue;
  const source = await readFile(resolve(referenceDir, entry), 'utf8');
  const names = [...source.matchAll(/export\s+(?:async\s+)?function\s+(mount[A-Za-z0-9_]*)\s*\(/g)].map(match => match[1]).filter(name => allowed.has(kindOf(name)));
  if (names.length) modules.push({ entry, names });
}
if (!modules.length) throw new Error(`No mount* exports found in internal-docs/reference/*.ts for: ${[...allowed].join(', ')}`);

const imports = modules.flatMap(({ entry, names }) => names.map(name => `import { ${name} } from '../../internal-docs/reference/${entry.slice(0, -3)}';`));
const registry = modules.flatMap(({ names }) => names.map(name => `  '${kindOf(name)}': ${name},`));
// Stylesheet order mirrors real VS Code layering: upstream codicon rules, then
// @vscode/codicons (glyphs), then VS Code's own modifiers so spin/disabled
// semantics match the workbench instead of the npm package's variants.
const entrySource = `// Generated by internal-docs/reference/standalone/build.mjs. Do not edit.
import '../../vscode/src/vs/workbench/browser/media/style.css';
import '../../vscode/src/vs/base/browser/ui/codicons/codicon/codicon.css';
import '@vscode/codicons/dist/codicon.css';
import '../../vscode/src/vs/base/browser/ui/codicons/codicon/codicon-modifiers.css';
import '../../vscode/src/vs/base/browser/ui/pixelSpinner/pixelSpinner.css';
import '../../internal-docs/reference/fixture.css';
${imports.join('\n')}

const registry: Record<string, (root: HTMLElement, surface: HTMLElement, state: any) => void> = {
${registry.join('\n')}
};

void (async () => {
const params = new URLSearchParams(location.search);
const theme = params.get('theme') || 'dark';
const colors = (await (await fetch('./themes.json')).json())[theme];
const root = document.querySelector<HTMLElement>('#fixture')!;
root.className = \`monaco-workbench \${/Mac/.test(navigator.platform) ? 'mac' : /Win/.test(navigator.platform) ? 'windows' : 'linux'} \${{ dark: 'vs-dark', light: 'vs', hcDark: 'hc-black', hcLight: 'hc-light' }[theme]}\`;
for (const [id, color] of Object.entries(colors)) root.style.setProperty(\`--vscode-\${id.replaceAll('.', '-')}\`, color as string);
const state: any = { focus: [], selection: [], expanded: [], clicks: 0, escapes: 0, actions: [] };
(window as any).fixtureState = state;
const outside = document.createElement('button');
outside.className = 'outside'; outside.textContent = 'Move focus outside';
const kind = params.get('kind') || ${JSON.stringify(kindOf(modules[0].names[0]))};
const surface = document.createElement('div');
surface.className = \`specimen \${kind !== 'tree' ? 'button-specimen' : 'tree-specimen'}\`;
surface.dataset.testid = 'specimen';
root.append(surface, outside);
const mount = registry[kind];
if (!mount) throw new Error(\`Unknown fixture kind: \${kind}. Known: \${Object.keys(registry).join(', ')}\`);
mount(root, surface, state);
(window as any).fixtureReady = true;
})().catch(error => { (window as any).fixtureError = String(error && error.stack || error); console.error(error); });
`;

await mkdir(at('.cache'), { recursive: true });
await mkdir(at('public/reference'), { recursive: true });
const entry = at('.cache/standalone-entry.ts');
await writeFile(entry, entrySource);
await build({
  absWorkingDir: root, entryPoints: [entry], outfile: 'public/reference/standalone.js', bundle: true,
  platform: 'browser', format: 'iife', nodePaths: [at('node_modules')], sourcemap: true, target: 'es2022',
  tsconfigRaw: { compilerOptions: { experimentalDecorators: true, useDefineForClassFields: false } },
  loader: { '.ttf': 'dataurl' },
  plugins: [{ name: 'clone-codicon-font', setup(build) {
    build.onResolve({ filter: /codicon\.ttf$/ }, () => ({ path: at('node_modules/@vscode/codicons/dist/codicon.ttf') }));
  } }],
});
await writeFile(at('public/reference/standalone.html'), '<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="./standalone.css"></head><body><div id="fixture"></div><script src="./standalone.js"></script></body></html>');
console.log(`Standalone verification fixtures bundled: ${modules.flatMap(m => m.names.map(kindOf)).join(', ')}`);
